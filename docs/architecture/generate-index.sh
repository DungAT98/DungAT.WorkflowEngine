#!/usr/bin/env bash
# generate-index.sh — build INDEX.md and GRAPH.md from the spec frontmatter in docs/architecture/<domain>/*.md.
# Run from anywhere:  bash docs/architecture/generate-index.sh
#
# Validates (prints DUPLICATE / WARNING / CYCLE and exits 1):
#   - every entry_points/commands symbol has exactly one owner spec
#   - every prerequisites/downstream/see_also target exists
#   - prerequisites + downstream <= 10 per spec
#   - prerequisites/downstream form no cycle
# Output is deterministic (sorted, no timestamps) so the spec-impact gate can compare it with the committed copy.
set -euo pipefail
export LC_ALL=C

cd "$(dirname "$0")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

find . -mindepth 2 -name '*.md' ! -name 'INDEX.md' ! -name 'GRAPH.md' | sed 's|^\./||' | sort > "$tmp/files"

# --- Stage 1: frontmatter -> tab-separated facts ---------------------------------------------
if [[ -s "$tmp/files" ]]; then
  # shellcheck disable=SC2046
  awk -F'\t' '
    function trim(s) { gsub(/^[ \t"\047]+|[ \t"\047]+$/, "", s); return s }
    function items(line, n, parts, i, out) {
      sub(/^[a-z_]+:[ \t]*\[/, "", line); sub(/\][ \t]*$/, "", line)
      n = split(line, parts, /,[ \t]*/)
      for (i = 1; i <= n; i++) { parts[i] = trim(parts[i]); if (parts[i] != "") emit(parts[i]) }
    }
    FNR == 1 { fm = 0; key = FILENAME; sub(/^\.\//, "", key); sub(/\.md$/, "", key); domain = key; sub(/\/.*/, "", domain); name = key; sub(/^[^\/]*\//, "", name) }
    /^---[ \t]*$/ { fm++; next }
    fm != 1 { next }
    /^description:/ { d = $0; sub(/^description:[ \t]*/, "", d); d = trim(d); gsub(/`/, "", d); gsub(/\|/, "/", d); print "SPEC\t" key "\t" domain "\t" name "\t" d; next }
    /^(entry_points|commands):/   { kind = "SYM";   items($0); next }
    /^prerequisites:/             { kind = "PRE";   items($0); next }
    /^downstream:/                { kind = "DOWN";  items($0); next }
    /^see_also:/                  { kind = "SEE";   items($0); next }
    /^events_out:/                { kind = "EVOUT"; items($0); next }
    /^events_in:/                 { kind = "EVIN";  items($0); next }
    function emit(v) {
      if (kind == "SYM") print "SYM\t" v "\t" key
      else if (kind == "EVOUT" || kind == "EVIN") print kind "\t" v "\t" key
      else print kind "\t" key "\t" v
    }
  ' $(sed 's|^|./|' "$tmp/files" | tr '\n' ' ') > "$tmp/facts.raw"
else
  : > "$tmp/facts.raw"
fi
sort -u "$tmp/facts.raw" > "$tmp/facts"

# --- Stage 2: validation -----------------------------------------------------------------------
errors=0
awk -F'\t' '
  $1 == "SPEC" { spec[$2] = 1 }
  $1 == "SYM"  { owner[$2] = owner[$2] " " $3; count[$2]++ }
  $1 == "PRE"  { links[$2]++; need[$2 "\t" $3] = "prerequisites"; edge[$3 "\t" $2] = 1 }
  $1 == "DOWN" { links[$2]++; need[$2 "\t" $3] = "downstream";     edge[$2 "\t" $3] = 1 }
  $1 == "SEE"  { need[$2 "\t" $3] = "see_also" }
  END {
    bad = 0
    for (s in owner) if (count[s] > 1) { print "DUPLICATE: " s " is owned by:" owner[s]; bad = 1 }
    for (n in need) { split(n, p, "\t"); if (!(p[2] in spec)) { print "WARNING: " p[1] " " need[n] " -> " p[2] " does not exist"; bad = 1 } }
    for (s in links) if (links[s] > 10) { print "WARNING: " s " has " links[s] " prerequisites+downstream (max 10)"; bad = 1 }

    # Cycle check (Kahn): whatever cannot be peeled off sits on a cycle.
    for (e in edge) { split(e, p, "\t"); out[p[1]] = out[p[1]] " " p[2]; indeg[p[2]]++; node[p[1]] = 1; node[p[2]] = 1 }
    for (x in node) if (!(x in indeg)) indeg[x] = 0
    qn = 0
    for (x in node) if (indeg[x] == 0) queue[++qn] = x
    for (qi = 1; qi <= qn; qi++) {
      m = split(out[queue[qi]], succ, " ")
      for (j = 1; j <= m; j++) if (--indeg[succ[j]] == 0) queue[++qn] = succ[j]
    }
    stuck = ""
    for (x in node) if (indeg[x] > 0) stuck = stuck " " x
    if (stuck != "") { print "CYCLE: prerequisites/downstream cycle involving:" stuck; bad = 1 }
    exit bad
  }
' "$tmp/facts" || errors=1

# --- Stage 3: INDEX.md -------------------------------------------------------------------------
{
  echo "# Architecture Index"
  echo
  echo "<!-- Generated by docs/architecture/generate-index.sh. Do not edit by hand. -->"
  echo
  echo "Start at [ROUTING.md](ROUTING.md). Lookup: \`grep -i <keyword> docs/architecture/INDEX.md\`."
  echo
  echo "## Specs"
  echo
  echo "| Domain | Spec | Description |"
  echo "|---|---|---|"
  awk -F'\t' '$1 == "SPEC" { printf "| %s | [%s.md](%s.md) | %s |\n", $3, $2, $2, $5 }' "$tmp/facts"
  echo
  echo "## By Entry Point / Command"
  echo
  awk -F'\t' '$1 == "SYM" { printf "- `%s` → [%s.md](%s.md)\n", $2, $3, $3 }' "$tmp/facts"
} > INDEX.md

# --- Stage 4: GRAPH.md -------------------------------------------------------------------------
{
  echo "# Architecture Graph"
  echo
  echo "<!-- Generated by docs/architecture/generate-index.sh. Do not edit by hand. -->"
  echo
  echo "## Flow links"
  echo
  echo "Edges read \"A → B\": B runs after A."
  echo
  awk -F'\t' '
    $1 == "DOWN" { print $2 " → " $3 }
    $1 == "PRE"  { print $3 " → " $2 }
  ' "$tmp/facts" | sort -u | sed 's/^/- /'
  echo
  echo "## Events"
  echo
  echo "| Event | Published by | Consumed by |"
  echo "|---|---|---|"
  awk -F'\t' '
    $1 == "EVOUT" { ev[$2] = 1; pub[$2] = pub[$2] (pub[$2] == "" ? "" : ", ") $3 }
    $1 == "EVIN"  { ev[$2] = 1; con[$2] = con[$2] (con[$2] == "" ? "" : ", ") $3 }
    END { for (e in ev) printf "| `%s` | %s | %s |\n", e, (pub[e] == "" ? "—" : pub[e]), (con[e] == "" ? "—" : con[e]) }
  ' "$tmp/facts" | sort
} > GRAPH.md

if (( errors )); then
  echo "generate-index.sh: validation failed" >&2
  exit 1
fi
specs=$(grep -c '^SPEC' "$tmp/facts" || true)
echo "generate-index.sh: OK ($specs specs)"
